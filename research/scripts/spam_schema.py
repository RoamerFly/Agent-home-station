"""Generate exact typed protobuf encoding from the frozen ABI's field tags."""
import contextlib,io,json,pathlib,re,runpy
ROOT=pathlib.Path(__file__).resolve().parents[2]
with contextlib.redirect_stdout(io.StringIO()):d=runpy.run_path(str(ROOT/'research/scripts/recover_newspam_v8_structs.py'))
types=[('SpamFileInfo',0xeb4d80),('SpamFileStat',0xecb280),('SpamStatFS',0xef74a0),('SpamBody',0xf582e0)]
out=['// Generated by research/scripts/spam_schema.py from frozen Go ABI tags.','// Schema reconstruction, not original source.','package deviceproof','import ("encoding/binary";"fmt")','const spamMaxWire = 2 << 20']
records=[]
for goname,address in types:
    f=d['u64'](address+56);count=d['u64'](address+64);fields=[]
    for i in range(count):
        a=f+i*24;name,tag=d['name'](d['u64'](a));typ=d['typename'](d['u64'](a+8))
        if not tag:continue
        m=re.search(r'protobuf:"(\w+),(\d+),(\w+),',tag)
        if not m:continue
        wire,num,presence=m.groups();num=int(num)
        typ=typ.replace('wechat.FileInfo','SpamFileInfo').replace('wechat.FileStat','SpamFileStat').replace('wechat.Statfs','SpamStatFS')
        fields.append((name,typ,wire,num,presence))
    records.append({'name':goname,'type_address':hex(address),'fields':[dict(zip(('name','type','wire','number','presence'),x)) for x in fields]})
    out.append('type '+goname+' struct {')
    for name,typ,wire,num,pres in fields:out.append(name+' '+typ+' // protobuf '+str(num)+' '+pres)
    out.append('}')
    out.append('func (v *'+goname+') MarshalBinary() ([]byte,error) { if v==nil{return nil,fmt.Errorf("deviceproof: nil '+goname+'")}')
    for name,typ,wire,num,pres in fields:
        if pres=='req':out.append('if v.'+name+'==nil{return nil,fmt.Errorf("deviceproof: missing '+goname+'.'+name+'")}')
    out.append('var out []byte')
    for name,typ,wire,num,pres in fields:
        ptr='v.'+name
        if pres=='rep':
            out.append('if len('+ptr+')>256{return nil,fmt.Errorf("deviceproof: too many '+name+'")}')
            out.append('for _,item:=range '+ptr+' {')
            if typ=='[]string':out.append('if len(item)>65536{return nil,fmt.Errorf("deviceproof: oversized string")};out=spamBytes(out,'+str(num)+',[]byte(item))')
            else:out.append('b,err:=item.MarshalBinary();if err!=nil{return nil,err};out=spamBytes(out,'+str(num)+',b)')
            out.append('}')
        else:
            out.append('if '+ptr+'!=nil{')
            if typ=='*string':out.append('if len(*'+ptr+')>65536{return nil,fmt.Errorf("deviceproof: oversized string")};out=spamBytes(out,'+str(num)+',[]byte(*'+ptr+'))')
            elif wire=='varint':out.append('out=spamInt(out,'+str(num)+',uint64(*'+ptr+'))')
            else:out.append('b,err:='+ptr+'.MarshalBinary();if err!=nil{return nil,err};out=spamBytes(out,'+str(num)+',b)')
            out.append('}')
        out.append('if len(out)>spamMaxWire{return nil,fmt.Errorf("deviceproof: oversized '+goname+'")}')
    out.append('return out,nil }')
out.extend(['func spamInt(out []byte,field int,v uint64)[]byte{out=binary.AppendUvarint(out,uint64(field<<3));return binary.AppendUvarint(out,v)}','func spamBytes(out []byte,field int,v []byte)[]byte{out=binary.AppendUvarint(out,uint64(field<<3|2));out=binary.AppendUvarint(out,uint64(len(v)));return append(out,v...)}'])
target=ROOT/'internal/deviceproof/spam_schema.go';target.parent.mkdir(exist_ok=True)
target.write_text('\n'.join(out)+'\n',encoding='utf8')
(ROOT/'research/evidence/spam-schema.json').write_text(json.dumps(records,indent=2)+'\n',encoding='utf8')
print('Generated',sum(len(r['fields']) for r in records),'fields.')
